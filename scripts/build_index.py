#!/usr/bin/env python3
"""Generate `wiki/index.md` from the pages on disk.

The index is the one file every reader opens first and the one file every ingest
changes. Generating it removes the "did I forget to add it?" step, and makes the
check mechanical:

    python scripts/build_index.py wiki/            # write wiki/index.md
    python scripts/build_index.py wiki/ --check    # exit 1 if it is out of date
    python scripts/build_index.py wiki/ --stdout   # print, write nothing

Standard library only. Page parsing is shared with wiki_lint.py.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from wiki_lint import collect, parse_frontmatter

TYPE_ORDER = ("source", "entity", "concept", "synthesis")
SECTION_TITLES = {
    "source": "Sources",
    "entity": "Entities",
    "concept": "Concepts",
    "synthesis": "Synthesis",
}

WIKILINK = re.compile(r"\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|([^\]]*))?\]\]")


def one_line(page, limit: int = 110) -> str:
    """First prose line of the body, flattened and shortened. Headings and
    bullets are skipped: a bullet is rarely a summary of the page."""
    for raw in page.body.splitlines():
        line = raw.strip()
        if not line or line.startswith(("#", ">", "-", "*", "|", "```", "<!--", "> ")):
            continue
        line = WIKILINK.sub(lambda m: m.group(2) or m.group(1), line)
        line = re.sub(r"[`*_]", "", line).strip()
        if line:
            return line if len(line) <= limit else line[: limit - 1].rstrip() + "…"
    return ""


def render(root: Path) -> str:
    pages = collect(root)
    for page in pages:
        parse_frontmatter(page)

    groups: dict[str, list] = {t: [] for t in TYPE_ORDER}
    for page in pages:
        ptype = page.meta.get("type")
        if not isinstance(ptype, str):
            continue  # lint reports the missing frontmatter; the index skips it
        groups.setdefault(ptype, []).append(page)

    out = [
        "# Index",
        "",
        "Every page in the wiki, one line each. Generated by `scripts/build_index.py` — "
        "edit the pages and re-run; do not hand-edit.",
        "",
        "Legend: `[[slug]]` — one-line what it is.",
        "",
    ]
    for ptype in list(TYPE_ORDER) + [t for t in groups if t not in TYPE_ORDER]:
        entries = sorted(groups.get(ptype, []), key=lambda p: p.slug)
        out.append(f"## {SECTION_TITLES.get(ptype, ptype.title())}")
        out.append("")
        if not entries:
            out.append("_None yet._")
            out.append("")
            continue
        for page in entries:
            title = str(page.meta.get("title") or "").strip()
            summary = one_line(page)
            if summary and title and summary.lower() != title.lower():
                out.append(f"- [[{page.slug}]] — {summary}")
            elif title:
                out.append(f"- [[{page.slug}]] — {title}")
            else:
                out.append(f"- [[{page.slug}]]")
        out.append("")

    out.append("## Outputs (outside the wiki)")
    out.append("")
    out.append("Destination layer, not part of the fact base: `outputs/<channel>/SPEC.md` and `state.md`.")
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate wiki/index.md from the pages on disk.")
    ap.add_argument("path", nargs="?", default="wiki", help="wiki directory (default: wiki)")
    ap.add_argument("--out", default=None, help="output file (default: <path>/index.md)")
    ap.add_argument("--check", action="store_true", help="exit 1 if the file on disk is stale")
    ap.add_argument("--stdout", action="store_true", help="print instead of writing")
    args = ap.parse_args(argv)

    root = Path(args.path)
    if not root.is_dir():
        print(f"not a directory: {root}", file=sys.stderr)
        return 2

    text = render(root)
    target = Path(args.out) if args.out else root / "index.md"

    if args.stdout:
        print(text)
        return 0
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current.strip() != text.strip():
            print(f"{target} is out of date — run: python scripts/build_index.py {root}", file=sys.stderr)
            return 1
        print(f"{target} is up to date.")
        return 0

    target.write_text(text, encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
